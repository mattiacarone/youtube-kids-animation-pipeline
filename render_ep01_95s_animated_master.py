"""
Assembles the 100% Genuine Animated Video for Pixieland Episode 01: "The Magic Compass"
- Full animated 3D video clips generated by Google Vids Omni
- Duration: ~90-95 seconds
- Resolution: 1920x1080 Full HD Landscape (16:9)
- Transitions: Seamless 0.8-second crossfades (xfade=fade) between all scenes
- Zero text on screen
- Audio: Master 95s soundtrack with natural child voice (en-US-AnaNeural),
  nature ambient, portal whoosh, compass chimes, and marimba/pizzicato music.
"""
import os
import subprocess
import imageio_ffmpeg
from moviepy import VideoFileClip

FFMPEG = imageio_ffmpeg.get_ffmpeg_exe()
SCENES_DIR = r"C:\Users\Mattia\YouTubeKids\ep01_landscape\scenes"
AUDIO_PATH = r"C:\Users\Mattia\YouTubeKids\ep01_landscape\audio\ep01_master_tight_soundtrack.wav"
OUT_VIDEO = r"C:\Users\Mattia\YouTubeKids\output\Pixieland_Episode01_The_Magic_Compass_Animated_95s.mp4"

ANIM_CLIPS = [
    "vids_scene1_garden.mp4",
    "vids_scene2_compass.mp4",
    "vids_scene3_portal.mp4",
    "vids_scene4_breath_courage.mp4",
    "vids_scene5_forest_arrival.mp4",
    "vids_scene6_bird_words.mp4",
    "vids_scene7_golden_leaf.mp4",
    "vids_scene8_explorer_journal.mp4",
    "vids_scene9_outro_farewell.mp4"
]

def render_animated_master():
    os.makedirs(os.path.dirname(OUT_VIDEO), exist_ok=True)
    full_clip_paths = []
    durations = []
    
    print("Checking all animated clips...")
    for c_name in ANIM_CLIPS:
        p = os.path.join(SCENES_DIR, c_name)
        if not os.path.exists(p) or os.path.getsize(p) < 100000:
            print(f"Error: Missing or incomplete clip {c_name}!")
            return False
        v = VideoFileClip(p)
        dur = v.duration
        v.close()
        full_clip_paths.append(p)
        durations.append(dur)
        print(f"  {c_name}: duration={dur:.2f}s, size={os.path.getsize(p)} bytes")
        
    print(f"\nTotal raw clips: {len(full_clip_paths)} | Total raw duration: {sum(durations):.2f}s")
    
    # Calculate crossfade offsets
    trans_dur = 0.8
    offsets = []
    cur_time = 0.0
    for dur in durations[:-1]:
        cur_time += dur - trans_dur
        offsets.append(cur_time)
        
    print(f"Crossfade offsets: {[round(o, 2) for o in offsets]}")
    
    # Complex filter for cascading xfades + 1080p scaling
    inputs = []
    for cp in full_clip_paths:
        inputs.extend(["-i", cp])
    inputs.extend(["-i", AUDIO_PATH])
    
    filter_parts = []
    # First scale all video inputs to 1920x1080 and 30fps
    for idx in range(len(full_clip_paths)):
        filter_parts.append(
            f"[{idx}:v]scale=1920:1080:force_original_aspect_ratio=increase,crop=1920:1080,fps=30,setsar=1[s{idx}]"
        )
        
    prev_label = "s0"
    for idx in range(1, len(full_clip_paths)):
        next_in = f"s{idx}"
        out_label = f"xf{idx}"
        offset = offsets[idx-1]
        filter_parts.append(
            f"[{prev_label}][{next_in}]xfade=transition=fade:duration={trans_dur}:offset={offset:.2f}[{out_label}]"
        )
        prev_label = out_label
        
    filter_complex = ";".join(filter_parts)
    
    cmd = [
        FFMPEG, "-y",
        *inputs,
        "-filter_complex", filter_complex,
        "-map", f"[{prev_label}]",
        "-map", f"{len(full_clip_paths)}:a",
        "-c:v", "libx264",
        "-preset", "medium",
        "-crf", "18",
        "-pix_fmt", "yuv420p",
        "-c:a", "aac",
        "-b:a", "192k",
        "-shortest",
        OUT_VIDEO
    ]
    
    print("\nAssembling Master Animated Episode via FFmpeg...")
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode == 0 and os.path.exists(OUT_VIDEO):
        size_mb = os.path.getsize(OUT_VIDEO) / (1024 * 1024)
        print("===========================================================")
        print(f"MASTER ANIMATED EPISODE 01 READY: {OUT_VIDEO}")
        print(f"File Size: {size_mb:.2f} MB")
        print("===========================================================")
        return True
    else:
        print(f"FFmpeg error: {res.stderr}")
        return False

if __name__ == "__main__":
    render_animated_master()
