"""
Renders the complete animated YouTube Short using the AI video clips generated by Google Vids.
"""
import os
import numpy as np
from PIL import Image, ImageDraw, ImageFont
from moviepy import VideoFileClip, AudioFileClip, CompositeVideoClip, concatenate_videoclips, ImageClip

W, H = 720, 1280
FPS = 30
FONT_PATH = r"C:\Windows\Fonts\comicbd.ttf"
if not os.path.exists(FONT_PATH):
    FONT_PATH = r"C:\Windows\Fonts\arialbd.ttf"

SCENES = [
    {
        "id": "scene1_hook",
        "video": "assets/clips/vids_penguin_walk.mp4",
        "audio": "assets/audio/cocomelon_scene1.mp3",
        "captions": [
            (0.0, 2.5, "❄️ LOOK! A PENGUIN! 🐧", "#FFD700"),
            (2.5, 5.2, "🐾 WADDLE WADDLE! 🐾", "#00E5FF")
        ]
    },
    {
        "id": "scene2_waddle",
        "video": "assets/clips/vids_scene2_waddle.mp4",
        "audio": "assets/audio/cocomelon_scene2.mp3",
        "captions": [
            (0.0, 3.5, "🪽 FLAP YOUR WINGS! 🪽", "#FF4081"),
            (3.5, 7.3, "⭐ SUPER PENGUIN! ⭐", "#FFEB3B")
        ]
    },
    {
        "id": "scene3_loop",
        "video": "assets/clips/vids_scene3_loop.mp4",
        "audio": "assets/audio/cocomelon_scene3.mp3",
        "captions": [
            (0.0, 3.0, "🎉 YAY! YOU DID IT! 🎉", "#00E676"),
            (3.0, 6.3, "✨ LET'S EXPLORE AGAIN! ✨", "#FFD700")
        ]
    }
]

def make_cocomelon_badge(text, text_color):
    """Creates a high-contrast bouncy bubble caption badge for toddlers."""
    overlay = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    draw = ImageDraw.Draw(overlay)
    
    font = ImageFont.truetype(FONT_PATH, 50)
    bbox = draw.textbbox((0, 0), text, font=font)
    tw = bbox[2] - bbox[0] + 80
    th = bbox[3] - bbox[1] + 50
    
    # Place pill in upper third
    x0 = (W - tw) // 2
    y0 = 110
    x1 = x0 + tw
    y1 = y0 + th
    
    # Thick shadow + bright white candy pill
    draw.rounded_rectangle([x0 + 6, y0 + 6, x1 + 6, y1 + 6], radius=30, fill=(0, 0, 0, 110))
    draw.rounded_rectangle([x0, y0, x1, y1], radius=30, fill=(255, 255, 255, 250), outline=(255, 204, 0, 255), width=7)
    
    # Text with heavy black stroke
    tx = (W - (bbox[2] - bbox[0])) // 2
    ty = y0 + 15
    
    for dx, dy in [(-3,-3), (3,-3), (-3,3), (3,3), (0,3), (0,-3), (3,0), (-3,0)]:
        draw.text((tx + dx, ty + dy), text, font=font, fill=(0, 0, 0, 255))
    draw.text((tx, ty), text, font=font, fill=text_color)
    
    return np.array(overlay)

def render_scene(cfg):
    audio = AudioFileClip(cfg["audio"])
    dur = audio.duration
    
    # Load the real video clip generated by Google Vids
    vclip = VideoFileClip(cfg["video"])
    # Subclip to match audio duration
    if vclip.duration > dur:
        vclip = vclip.subclipped(0, dur)
    else:
        dur = vclip.duration
        
    layers = [vclip]
    for start_t, end_t, text, color in cfg["captions"]:
        c_dur = min(end_t, dur) - start_t
        if c_dur <= 0:
            continue
        badge_np = make_cocomelon_badge(text, color)
        badge_clip = ImageClip(badge_np, duration=c_dur).with_start(start_t)
        layers.append(badge_clip)
        
    return CompositeVideoClip(layers, size=(W, H)).with_duration(dur).with_audio(audio)

def main():
    os.makedirs("output", exist_ok=True)
    out_path = "output/Pixieland_Google_Vids_Short.mp4"
    
    print("Assembling video scenes from Google Vids AI animations...")
    scene_clips = [render_scene(cfg) for cfg in SCENES]
    final_video = concatenate_videoclips(scene_clips, method="compose")
    
    print(f"Total video duration: {final_video.duration:.2f}s")
    print(f"Exporting to {out_path}...")
    final_video.write_videofile(
        out_path,
        fps=FPS,
        codec="libx264",
        audio_codec="aac",
        threads=4,
        preset="fast"
    )
    print(f"\n[SUCCESS] Final Google Vids Animated Short exported to: {out_path}")

if __name__ == "__main__":
    main()
